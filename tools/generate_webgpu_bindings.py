#!/usr/bin/env python3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADER = ROOT / "src/NoorRHI/Shaders/NoorRHIWebGpu.slang"
HEADER = ROOT / "src/NoorRHI/WebGpu/WebGpuBindings.h"

HEAP_BINDING = 0
ATOMIC_BINDING = 1
HEAP_READ_BINDING = 2
ARGUMENT_GROUP = 1
ARGUMENT_BINDING = 0
FIRST_POOL_BINDING = 3
LAYER_BITS = 16
STORAGE_EXTENT_ADDRESS = 256
STORAGE_LAYER_CAPACITY = 256
TEXTURE_TABLE_CAPACITY = 65536
SAMPLER_NEAREST_BIT = 16
SAMPLER_ANISOTROPY_SHIFT = 5

#! Chrome gives at most 48 sampled textures per stage.
SAMPLED_POOLS = [("Float", 40, "float4"), ("Unfilterable", 4, "float4"), ("Uint", 4, "uint4")]
STORAGE_POOLS = [("Rgba8Unorm", "rgba8", "float4"), ("Rgba16Float", "rgba16f", "float4"), ("R32Float", "r32f", "float4"), ("R32Uint", "r32ui", "uint4"),
                 ("Rgba32Float", "rgba32f", "float4"), ("R16Float", "r16f", "float4"), ("R8Unorm", "r8", "float4")]
TEXTURE_TABLE_ADDRESS = STORAGE_EXTENT_ADDRESS + len(STORAGE_POOLS) * STORAGE_LAYER_CAPACITY * 8


def assign_bindings():
    binding = FIRST_POOL_BINDING
    sampled = []
    for kind, count, texel in SAMPLED_POOLS:
        sampled.append((kind, [binding + index for index in range(count)], texel))
        binding += count
    sampler = binding
    binding += 1
    storage = []
    for kind, slangFormat, texel in STORAGE_POOLS:
        storage.append((kind, binding, slangFormat, texel))
        binding += 1
    return sampled, sampler, storage, binding


def pool_name(binding):
    return f"noorrhi_pool_{binding}"


def write_switch(lines, signature, cases, fallback, selector=f"handle >> {LAYER_BITS}"):
    lines.append("[noinline]")
    lines.append(signature + " {")
    lines.append(f"    switch ({selector}) {{")
    for binding, statement in cases:
        lines.append(f"    case {binding}: {statement}")
    lines.append(f"    default: {fallback}")
    lines.append("    }")
    lines.append("}")
    lines.append("")


def generate_shader():
    sampled, sampler, storage, _ = assign_bindings()
    layer = f"(handle & {(1 << LAYER_BITS) - 1}u)"
    lines = ["//! Generated by tools/generate_webgpu_bindings.py.", ""]
    lines.append(f"[vk::binding({HEAP_BINDING}, 0)] RWByteAddressBuffer noorrhi_heap;")
    lines.append(f"[vk::binding({ATOMIC_BINDING}, 0)] RWStructuredBuffer<Atomic<uint>> noorrhi_atomics;")
    lines.append(f"[vk::binding({HEAP_READ_BINDING}, 0)] ByteAddressBuffer noorrhi_heap_read;")
    lines.append(f"[vk::binding({ARGUMENT_BINDING}, {ARGUMENT_GROUP})] ByteAddressBuffer noorrhi_arguments;")
    for _, bindings, texel in sampled:
        for binding in bindings:
            lines.append(f"[vk::binding({binding}, 0)] Texture2DArray<{texel}> {pool_name(binding)};")
    lines.append(f"[vk::binding({sampler}, 0)] SamplerState noorrhi_sampler;")
    for _, binding, slangFormat, texel in storage:
        lines.append(f'[format("{slangFormat}")] [vk::binding({binding}, 0)] RWTexture2DArray<{texel}> {pool_name(binding)};')
    lines.append("")

    floatPools = sampled[0][1]
    loadPools = sampled[0][1] + sampled[1][1]
    uintPools = sampled[2][1]
    floatStorage = [binding for _, binding, _, texel in storage if texel == "float4"]
    uintStorage = [binding for _, binding, _, texel in storage if texel == "uint4"]

    def pool_cases(call):
        cases = []
        for binding in floatPools:
            dimensions = f"uint width, height, layers; {pool_name(binding)}.GetDimensions(width, height, layers); float2 scale = 1.0 / float2(width, height);"
            cases.append((binding, f"{{ {dimensions} return {pool_name(binding)}.{call}; }}"))
        return cases

    location = "float3(texel * scale, layer)"
    write_switch(lines, "float4 noorrhi_sample_level_pool(uint binding, float2 texel, float layer, float lod)",
                 pool_cases(f"SampleLevel(noorrhi_sampler, {location}, lod)"), "return float4(0.0);", "binding")
    write_switch(lines, "float4 noorrhi_sample_grad_pool(uint binding, float2 texel, float layer, float2 dx, float2 dy)",
                 pool_cases(f"SampleGrad(noorrhi_sampler, {location}, dx * scale, dy * scale)"), "return float4(0.0);", "binding")

    load = "Load(int4(coord, layer, mip))"
    write_switch(lines, "float4 noorrhi_load_pool(uint binding, int2 coord, int layer, int mip)",
                 [(binding, f"return {pool_name(binding)}.{load};") for binding in loadPools], "return float4(0.0);", "binding")
    write_switch(lines, "uint4 noorrhi_load_uint_pool(uint binding, int2 coord, int layer, int mip)",
                 [(binding, f"return {pool_name(binding)}.{load};") for binding in uintPools], "return uint4(0);", "binding")

    texel = f"uint3(coord, {layer})"
    write_switch(lines, "float4 noorrhi_storage_load(uint handle, uint2 coord)",
                 [(binding, f"return {pool_name(binding)}[{texel}];") for binding in floatStorage], "return float4(0.0);")
    write_switch(lines, "void noorrhi_storage_store(uint handle, uint2 coord, float4 value)",
                 [(binding, f"{pool_name(binding)}[{texel}] = value; return;") for binding in floatStorage], "return;")
    write_switch(lines, "uint4 noorrhi_storage_load_uint(uint handle, uint2 coord)",
                 [(binding, f"return {pool_name(binding)}[{texel}];") for binding in uintStorage], "return uint4(0);")
    write_switch(lines, "void noorrhi_storage_store_uint(uint handle, uint2 coord, uint4 value)",
                 [(binding, f"{pool_name(binding)}[{texel}] = value; return;") for binding in uintStorage], "return;")

    firstStorage = storage[0][1]
    lines.append("uint2 noorrhi_storage_dimensions(uint handle) {")
    lines.append(f"    uint index = ((handle >> {LAYER_BITS}) - {firstStorage}u) * {STORAGE_LAYER_CAPACITY}u + {layer};")
    lines.append(f"    return noorrhi_heap.Load<uint2>({STORAGE_EXTENT_ADDRESS}u + index * 8u);")
    lines.append("}")
    lines.append("")
    lines.append(f"static const uint noorrhi_texture_table = {TEXTURE_TABLE_ADDRESS}u;")
    lines.append(f"static const uint noorrhi_sampler_nearest_bit = {SAMPLER_NEAREST_BIT}u;")
    lines.append(f"static const uint noorrhi_sampler_anisotropy_shift = {SAMPLER_ANISOTROPY_SHIFT}u;")
    return "\n".join(lines) + "\n"


def generate_header():
    sampled, sampler, storage, end = assign_bindings()
    lines = ["//! Generated by tools/generate_webgpu_bindings.py.", "#pragma once", "", "#include <array>", "#include <cstdint>", "",
             "namespace NoorRHI::Backend {", ""]
    lines.append(f"inline constexpr std::uint32_t heapBinding = {HEAP_BINDING};")
    lines.append(f"inline constexpr std::uint32_t atomicBinding = {ATOMIC_BINDING};")
    lines.append(f"inline constexpr std::uint32_t heapReadBinding = {HEAP_READ_BINDING};")
    lines.append(f"inline constexpr std::uint32_t argumentGroup = {ARGUMENT_GROUP};")
    lines.append(f"inline constexpr std::uint32_t argumentBinding = {ARGUMENT_BINDING};")
    lines.append(f"inline constexpr std::uint32_t layerBits = {LAYER_BITS};")
    lines.append(f"inline constexpr std::uint64_t storageExtentAddress = {STORAGE_EXTENT_ADDRESS};")
    lines.append(f"inline constexpr std::uint32_t storageLayerCapacity = {STORAGE_LAYER_CAPACITY};")
    lines.append(f"inline constexpr std::uint64_t textureTableAddress = {TEXTURE_TABLE_ADDRESS};")
    lines.append(f"inline constexpr std::uint32_t textureTableCapacity = {TEXTURE_TABLE_CAPACITY};")
    lines.append(f"inline constexpr std::uint32_t samplerNearestBit = {SAMPLER_NEAREST_BIT};")
    lines.append(f"inline constexpr std::uint32_t samplerAnisotropyShift = {SAMPLER_ANISOTROPY_SHIFT};")
    lines.append(f"inline constexpr std::uint32_t bindingCount = {end};")
    lines.append("")
    lines.append("enum class PoolKind : std::uint8_t { " + ", ".join(kind for kind, _, _ in SAMPLED_POOLS) + " };")
    lines.append("enum class StorageKind : std::uint8_t { " + ", ".join(pool[0] for pool in STORAGE_POOLS) + " };")
    lines.append("")
    lines.append("struct PoolBindings {")
    lines.append("    std::uint32_t first = 0;")
    lines.append("    std::uint32_t count = 0;")
    lines.append("};")
    lines.append("")
    entries = ", ".join(f"PoolBindings{{{bindings[0]}, {len(bindings)}}}" for _, bindings, _ in sampled)
    lines.append(f"inline constexpr std::array<PoolBindings, {len(sampled)}> sampledPoolBindings{{{entries}}};")
    lines.append(f"inline constexpr std::uint32_t samplerBinding = {sampler};")
    lines.append(f"inline constexpr PoolBindings storagePoolBindings{{{storage[0][1]}, {len(storage)}}};")
    lines.append(f"inline constexpr std::uint32_t sampledTextureCount = {sum(len(bindings) for _, bindings, _ in sampled)};")
    lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


SHADER.write_text(generate_shader())
HEADER.parent.mkdir(parents=True, exist_ok=True)
HEADER.write_text(generate_header())
